from crewai import Task

# ============================================================
#  完整 6 Agent 工作流任务定义 (工厂模式)
# ============================================================

def create_grounding_task(agent):
    """创建 Grounding 任务 (CKO)"""
    return Task(
        description='''分析用户需求并定义清晰的任务协议。
        1. 如果用户输入仅为问候（如"你好"），请礼貌回复并提出 3-5 个结构化追问。
        2. 如果用户提供了具体需求，请输出详细的任务协议（包含功能、技术栈等）。
        3. 输出必须使用简体中文。''',
        expected_output='简体中文编写的任务协议或结构化追问。',
        agent=agent,
        human_input=False
    )

